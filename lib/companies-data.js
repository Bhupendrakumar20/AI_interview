export const getCompanyById = (id) => {
  return COMPANIES_WITH_POSITIONS.find(
    (company) => company.id === id.toLowerCase()
  );
};

export const getPositionsForCompany = (companyId) => {
  const company = getCompanyById(companyId);
  return company ? company.positions : [];
};
